export function t(lang: Lang, key: string, replacements?: Record<string, string>): string {
  let value = translations[lang]?.[key] ?? key;
  if (replacements) {
    for (const [k, v] of Object.entries(replacements)) {
      value = value.replace(`{${k}}`, v);
    }
  }
  return value;
}
